import { Injectable, NotFoundException } from '@nestjs/common';
import { ConfigService } from '@nestjs/config';
import { randomUUID } from 'crypto';
import { createReadStream } from 'fs';
import { access, mkdir, unlink, writeFile } from 'fs/promises';
import { dirname, resolve, sep } from 'path';
import { Readable } from 'stream';
import { StorageService } from './storage.service';

@Injectable()
export class LocalStorageService extends StorageService {
  private readonly root: string;

  constructor(cfg: ConfigService) {
    super();
    this.root = resolve(cfg.get<string>('UPLOAD_DIR', './uploads'));
  }

  // Keys are generated by us, but we still make sure a key can never escape the upload folder.
  private pathFor(key: string) {
    const full = resolve(this.root, key);
    if (!full.startsWith(this.root + sep)) throw new Error('Invalid storage key');
    return full;
  }

  async save(folder: string, file: { buffer: Buffer; ext: string }) {
    const key = `${folder}/${randomUUID()}.${file.ext}`;
    const full = this.pathFor(key);
    await mkdir(dirname(full), { recursive: true });
    await writeFile(full, file.buffer);
    return key;
  }

  async open(key: string): Promise<Readable> {
    const full = this.pathFor(key);
    try {
      await access(full);
    } catch {
      throw new NotFoundException('File is missing from storage');
    }
    return createReadStream(full);
  }

  async delete(key: string) {
    try {
      await unlink(this.pathFor(key));
    } catch {
      /* already gone: fine */
    }
  }
}
